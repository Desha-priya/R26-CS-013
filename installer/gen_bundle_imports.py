"""
gen_bundle_imports.py  —  tell PyInstaller about every package the layers use
------------------------------------------------------------------------------
The layers are bundled as plain source files and executed at run time (see
gateway/layer_host.py), so PyInstaller's static analysis of the exe's entry point
never sees what THEY import. This script scans the layers' sources, finds every
third-party top-level package they import, and writes gateway/_bundled_imports.py:
a module that imports them all, guarded so it never executes. PyInstaller follows
those imports and bundles the packages.

Run by build_all.py with the build environment's python (so that find_spec tells
us what is really installed). Output is deterministic and safe to commit.
"""
import ast
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "gateway" / "_bundled_imports.py"

SCAN = [
    ROOT / "core" / "srC",
    ROOT / "layers" / "network",
    ROOT / "layers" / "ransomware" / "main.py",
    ROOT / "layers" / "ransomware" / "src",
    ROOT / "layers" / "content" / "demo",
    ROOT / "layers" / "content" / "src",
    ROOT / "gateway",
    ROOT / "neurashield_app.py",
]
# training / evaluation / dataset scripts are not part of the running product
SKIP_NAME = re.compile(r"(^|_)(train|eval|test)|loader|_acc|Acc|video_acc|^2|__pycache__|_bundled_imports", re.I)
SKIP_DIR = {"tests", "tools", "__pycache__", "docs", "demo_routes"}
# always bundle (dynamic imports that no scanner can see)
ALWAYS = [
    "uvicorn.logging", "uvicorn.loops.auto", "uvicorn.protocols.http.auto",
    "uvicorn.protocols.websockets.auto", "uvicorn.lifespan.on",
    "multipart", "python_multipart", "waitress", "win32crypt", "win32api",
    "pynput.keyboard._win32", "pynput.mouse._win32",
    "sklearn.ensemble._forest", "sklearn.ensemble._iforest",
    "sklearn.utils._typedefs", "sklearn.neighbors._partition_nodes",
    "scapy.all", "scapy.layers.all", "h5py", "tf_keras", "tensorflow",
    "transformers", "pystray._win32", "webview", "win11toast",
]


def files():
    for base in SCAN:
        if base.is_file():
            yield base
            continue
        for p in base.rglob("*.py"):
            if SKIP_DIR & set(p.relative_to(base).parts[:-1]) or SKIP_NAME.search(p.stem):
                continue
            yield p


def local_names():
    names = set()
    for base in SCAN:
        d = base if base.is_dir() else base.parent
        for p in d.iterdir():
            names.add(p.stem if p.suffix == ".py" else p.name)
    names |= {"src", "demo", "gateway"}
    return names


def main():
    stdlib = set(sys.stdlib_module_names)
    local = local_names()
    found = set()
    for f in files():
        try:
            tree = ast.parse(f.read_text(encoding="utf-8", errors="replace"))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            # keep the FULL dotted path: "import fastapi" alone does not make
            # PyInstaller bundle fastapi.middleware.cors, which the layer needs
            if isinstance(node, ast.Import):
                found |= {a.name for a in node.names}
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                found.add(node.module)
                found |= {f"{node.module}.{a.name}" for a in node.names if a.name != "*"}
    third = sorted(n for n in found
                   if n.split(".")[0] not in stdlib and n.split(".")[0] not in local)
    present, missing = [], []
    for n in third:
        try:
            ok = importlib.util.find_spec(n) is not None
        except Exception:
            ok = False   # "from pkg import name" where name is an attribute, not a module
        (present if ok else missing).append(n)
    if missing:
        print("  note: imported by the sources but not installed here (skipped): " + ", ".join(missing))
    lines = [
        '"""GENERATED by installer/gen_bundle_imports.py - do not edit.',
        "",
        "Never executed: it exists so PyInstaller bundles every package the layers import.",
        '"""',
        "",
        'if __name__ == "__bundle_analysis__":',
    ]
    for n in present:
        lines += [f"    try:", f"        import {n}", f"    except Exception:", f"        pass"]
    for n in ALWAYS:
        lines += [f"    try:", f"        import {n}", f"    except Exception:", f"        pass"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  wrote {OUT.relative_to(ROOT)}: {len(present)} scanned + {len(ALWAYS)} forced imports")


if __name__ == "__main__":
    main()
