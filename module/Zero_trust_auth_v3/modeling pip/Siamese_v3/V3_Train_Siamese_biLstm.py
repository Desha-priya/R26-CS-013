# NPZ LOADER
# ============================================================

def load_npz_sequence(path):

    if not path.exists():

        raise FileNotFoundError(
            f"Sequence file not found:\n{path}"
        )

    data = np.load(
        path,
        allow_pickle=False
    )

    keys = list(data.keys())

    # --------------------------------------------------------
    # Prefer common sequence-array names.
    # --------------------------------------------------------

    preferred_keys = [
        "X",
        "x",
        "sequence",
        "features",
        "data",
        "arr_0",
    ]

    array = None

    for key in preferred_keys:

        if key in data:

            candidate = data[key]

            if isinstance(candidate, np.ndarray):

                array = candidate
                break

    # --------------------------------------------------------
    # If no preferred key, search for 2D array.
    # --------------------------------------------------------

    if array is None:

        candidates = []

        for key in keys:

            candidate = data[key]

            if (
                isinstance(candidate, np.ndarray)
                and candidate.ndim == 2
            ):

                candidates.append(candidate)

        if len(candidates) == 1:

            array = candidates[0]

        elif len(candidates) > 1:

            raise ValueError(
                f"Multiple possible sequence arrays in {path}: "
                f"{keys}"
            )

    if array is None:

        raise ValueError(
            f"Could not identify sequence array in:\n"
            f"{path}\n"
            f"Available keys: {keys}"
        )

    array = np.asarray(
        array,
        dtype=np.float32
    )

    # --------------------------------------------------------
    # Shape validation
    # --------------------------------------------------------

    if array.shape != (
        SEQUENCE_LENGTH,
        FEATURE_COUNT
    ):

        raise ValueError(
            f"Invalid sequence shape in:\n"
            f"{path}\n"
            f"Expected: "
            f"({SEQUENCE_LENGTH}, {FEATURE_COUNT})\n"
            f"Got: {array.shape}"
        )

    if not np.all(np.isfinite(array)):

        raise ValueError(
            f"NaN/Inf detected in:\n{path}"
        )

    return array


# ============================================================
# NORMALIZATION
# ============================================================

def normalize_sequence(
    sequence,
    mean,
    std
):

    sequence = (
        sequence - mean
    ) / std

    if not np.all(
        np.isfinite(sequence)
    ):

        raise ValueError(
            "Normalization produced NaN/Inf."
        )

    return sequence.astype(
        np.float32
    )


