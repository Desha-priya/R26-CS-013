# PAIR DATASET
# ============================================================

class SiamesePairDataset(Dataset):

    def __init__(
        self,
        pair_csv,
        mean,
        std,
    ):

        self.pairs = pd.read_csv(
            pair_csv
        )

        self.mean = mean
        self.std = std

        required_columns = [
            "pair_id",
            "sequence_1",
            "sequence_2",
            "participant_1",
            "participant_2",
            "label",
            "pair_type",
        ]

        missing = [
            c
            for c in required_columns
            if c not in self.pairs.columns
        ]

        if missing:

            raise ValueError(
                f"Missing pair columns: {missing}"
            )

        if len(self.pairs) == 0:

            raise ValueError(
                f"Empty pair file: {pair_csv}"
            )

        # ----------------------------------------------------
        # Validate labels before training.
        # ----------------------------------------------------

        for _, row in self.pairs.iterrows():

            label = int(row["label"])

            p1 = int(
                row["participant_1"]
            )

            p2 = int(
                row["participant_2"]
            )

            if label == 1 and p1 != p2:

                raise ValueError(
                    "Invalid positive pair detected."
                )

            if label == 0 and p1 == p2:

                raise ValueError(
                    "Invalid negative pair detected."
                )

        self.base_dir = BASE_DIR

    def __len__(self):

        return len(self.pairs)

    def __getitem__(self, index):

        row = self.pairs.iloc[index]

        path1 = (
            self.base_dir
            / row["sequence_1"]
        )

        path2 = (
            self.base_dir
            / row["sequence_2"]
        )

        x1 = load_npz_sequence(
            path1
        )

        x2 = load_npz_sequence(
            path2
        )

        x1 = normalize_sequence(
            x1,
            self.mean,
            self.std
        )

        x2 = normalize_sequence(
            x2,
            self.mean,
            self.std
        )

        label = np.float32(
            row["label"]
        )

        return (
            torch.from_numpy(x1),
            torch.from_numpy(x2),
            torch.tensor(
                label,
                dtype=torch.float32
            ),
        )


# ============================================================
# SIAMESE BiLSTM ENCODER
# ============================================================

class BiLSTMEncoder(nn.Module):

    def __init__(self):

        super().__init__()

        self.lstm = nn.LSTM(
            input_size=FEATURE_COUNT,
            hidden_size=LSTM_HIDDEN_SIZE,
            num_layers=LSTM_LAYERS,
            batch_first=True,
            bidirectional=True,
            dropout=DROPOUT
            if LSTM_LAYERS > 1
            else 0.0,
        )

        self.embedding = nn.Sequential(

            nn.Linear(
                LSTM_HIDDEN_SIZE * 2,
                128
            ),

            nn.ReLU(),

            nn.Dropout(
                DROPOUT
            ),

            nn.Linear(
                128,
                EMBEDDING_SIZE
            ),
        )

    def forward(self, x):

        output, _ = self.lstm(x)

        # Last timestep representation.
        last_output = output[:, -1, :]

        embedding = self.embedding(
            last_output
        )

        # L2 normalization makes the embedding
        # suitable for distance-based comparison.
        embedding = nn.functional.normalize(
            embedding,
            p=2,
            dim=1
        )

        return embedding


# ============================================================
# SIAMESE NETWORK
# ============================================================

class SiameseBiLSTM(nn.Module):

    def __init__(self):

        super().__init__()

        # IMPORTANT:
        #
        # There is ONE encoder object.
        #
        # Both sequences therefore use exactly
        # the same weights.

        self.encoder = BiLSTMEncoder()

    def forward(
        self,
        x1,
        x2
    ):

        embedding1 = self.encoder(
            x1
        )

        embedding2 = self.encoder(
            x2
        )

        distance = torch.norm(
            embedding1 - embedding2,
            p=2,
            dim=1
        )

        return (
            embedding1,
            embedding2,
            distance
        )


# ============================================================
# CONTRASTIVE LOSS
# ============================================================

class ContrastiveLoss(nn.Module):

    def __init__(
        self,
        margin=1.0
    ):

        super().__init__()

        self.margin = margin

    def forward(
        self,
        distance,
        label
    ):

        # label = 1:
        # same participant
        # minimize distance
        #
        # label = 0:
        # different participant
        # push distance beyond margin

        positive_loss = (
            label
            * torch.pow(distance, 2)
        )

        negative_loss = (
            (1 - label)
            * torch.pow(
                torch.clamp(
                    self.margin - distance,
                    min=0.0
                ),
                2
            )
        )

        loss = (
            positive_loss
            + negative_loss
        )

        return loss.mean()


# ============================================================
# METRICS
# ============================================================

def calculate_pair_metrics(
    distances,
    labels,
    threshold
):

    distances = np.asarray(
        distances
    )

    labels = np.asarray(
        labels
    )

    predictions = (
        distances <= threshold
    ).astype(int)

    genuine = (
        labels == 1
    )

    impostor = (
        labels == 0
    )

    tp = np.sum(
        predictions[genuine] == 1
    )

    fn = np.sum(
        predictions[genuine] == 0
    )

    fp = np.sum(
        predictions[impostor] == 1
    )

    tn = np.sum(
        predictions[impostor] == 0
    )

    tpr = (
        tp / (tp + fn)
        if (tp + fn) > 0
        else 0.0
    )

    fpr = (
        fp / (fp + tn)
        if (fp + tn) > 0
        else 0.0
    )

    fnr = (
        fn / (tp + fn)
        if (tp + fn) > 0
        else 0.0
    )

    accuracy = (
        (tp + tn)
        /
        (tp + tn + fp + fn)
    )

    return {
        "threshold": float(threshold),
        "accuracy": float(accuracy),
        "tpr": float(tpr),
        "fpr": float(fpr),
        "fnr": float(fnr),
        "tp": int(tp),
        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
    }


# ============================================================
# FIND VALIDATION THRESHOLD
# ============================================================

def find_best_validation_threshold(
    distances,
    labels
):

    distances = np.asarray(
        distances
    )

    labels = np.asarray(
        labels
    )

    thresholds = np.linspace(
        distances.min(),
        distances.max(),
        501
    )

    best = None

    for threshold in thresholds:

        metrics = calculate_pair_metrics(
            distances,
            labels,
            threshold
        )

        if (
            best is None
            or metrics["accuracy"]
            > best["accuracy"]
        ):

            best = metrics

    return best


# ============================================================
# EER THRESHOLD
# ============================================================

def find_eer(
    distances,
    labels
):

    distances = np.asarray(
        distances
    )

    labels = np.asarray(
        labels
    )

    thresholds = np.linspace(
        distances.min(),
        distances.max(),
        2001
    )

    best = None

    for threshold in thresholds:

        metrics = calculate_pair_metrics(
            distances,
            labels,
            threshold
        )

        difference = abs(
            metrics["fpr"]
            - metrics["fnr"]
        )

        if (
            best is None
            or difference
            < best["difference"]
        ):

            best = {
                "threshold": float(
                    threshold
                ),
                "far": metrics["fpr"],
                "frr": metrics["fnr"],
                "difference": float(
                    difference
                ),
            }

    best["eer"] = (
        best["far"]
        + best["frr"]
    ) / 2.0

    return best


# ============================================================
# TRAIN ONE EPOCH
# ============================================================

def train_one_epoch(
    model,
    loader,
    optimizer,
    criterion
):

    model.train()

    total_loss = 0.0

    total_samples = 0

    for x1, x2, labels in loader:

        x1 = x1.to(
            DEVICE,
            non_blocking=True
        )

        x2 = x2.to(
            DEVICE,
            non_blocking=True
        )

        labels = labels.to(
            DEVICE,
            non_blocking=True
        )

        optimizer.zero_grad(
            set_to_none=True
        )

        _, _, distance = model(
            x1,
            x2
        )

        loss = criterion(
            distance,
            labels
        )

        loss.backward()

        torch.nn.utils.clip_grad_norm_(
            model.parameters(),
            max_norm=5.0
        )

        optimizer.step()

        batch_size = (
            labels.size(0)
        )

        total_loss += (
            loss.item()
            * batch_size
        )

        total_samples += batch_size

    return (
        total_loss
        / total_samples
    )


# ============================================================
# EVALUATION
# ============================================================

def evaluate(
    model,
    loader,
    criterion,
    threshold=None
):

    model.eval()

    total_loss = 0.0

    total_samples = 0

    all_distances = []

    all_labels = []

    with torch.no_grad():

        for x1, x2, labels in loader:

            x1 = x1.to(
                DEVICE,
                non_blocking=True
            )

            x2 = x2.to(
                DEVICE,
                non_blocking=True
            )

            labels = labels.to(
                DEVICE,
                non_blocking=True
            )

            _, _, distance = model(
                x1,
                x2
            )

            loss = criterion(
                distance,
                labels
            )

            batch_size = (
                labels.size(0)
            )

            total_loss += (
                loss.item()
                * batch_size
            )

            total_samples += batch_size

            all_distances.extend(
                distance.cpu().numpy()
            )

            all_labels.extend(
                labels.cpu().numpy()
            )

    mean_loss = (
        total_loss
        / total_samples
    )

    all_distances = np.asarray(
        all_distances
    )

    all_labels = np.asarray(
        all_labels
    ).astype(int)

    result = {
        "loss": float(mean_loss),
        "distances": all_distances,
        "labels": all_labels,
    }

    if threshold is not None:

        result["metrics"] = (
            calculate_pair_metrics(
                all_distances,
                all_labels,
                threshold
            )
        )

    return result


