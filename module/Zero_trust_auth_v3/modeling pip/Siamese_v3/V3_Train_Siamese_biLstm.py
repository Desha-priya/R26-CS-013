def load_train_scaler():

    if not SCALER_FILE.exists():

        raise FileNotFoundError(
            f"\nTRAIN-ONLY SCALER NOT FOUND:\n"
            f"{SCALER_FILE}\n\n"
            f"Do NOT train without the train-only scaler."
        )

    scaler = np.load(
        SCALER_FILE,
        allow_pickle=False
    )

    print()
    print("=" * 70)
    print("TRAIN-ONLY NORMALIZATION SCALER")
    print("=" * 70)

    print(
        "Scaler file:",
        SCALER_FILE
    )

    print(
        "Available arrays:",
        list(scaler.keys())
    )

    # --------------------------------------------------------
    # Try common naming conventions.
    # --------------------------------------------------------

    mean_keys = [
        "mean",
        "means",
        "feature_mean",
        "feature_means",
        "train_mean",
        "train_means",
    ]

    std_keys = [
        "std",
        "stds",
        "feature_std",
        "feature_stds",
        "train_std",
        "train_stds",
    ]

    mean = None
    std = None

    for key in mean_keys:

        if key in scaler:

            mean = scaler[key]
            break

    for key in std_keys:

        if key in scaler:

            std = scaler[key]
            break

    if mean is None or std is None:

        raise RuntimeError(
            "\nCould not identify mean/std arrays in the "
            "train-only scaler.\n\n"
            f"Available arrays: {list(scaler.keys())}\n\n"
            "Inspect the scaler file before training."
        )

    mean = np.asarray(
        mean,
        dtype=np.float32
    ).reshape(-1)

    std = np.asarray(
        std,
        dtype=np.float32
    ).reshape(-1)

    if len(mean) != FEATURE_COUNT:

        raise ValueError(
            f"Scaler mean has {len(mean)} features; "
            f"expected {FEATURE_COUNT}."
        )

    if len(std) != FEATURE_COUNT:

        raise ValueError(
            f"Scaler std has {len(std)} features; "
            f"expected {FEATURE_COUNT}."
        )

    if not np.all(np.isfinite(mean)):

        raise ValueError(
            "Scaler mean contains NaN/Inf."
        )

    if not np.all(np.isfinite(std)):

        raise ValueError(
            "Scaler std contains NaN/Inf."
        )

    if np.any(std <= 0):

        raise ValueError(
            "Scaler contains zero/negative standard deviation."
        )

    print(
        "Features:",
        len(mean)
    )

    print(
        "Scaler source: TRAIN ONLY"
    )

    print(
        "Validation used for scaler: NO"
    )

    print(
        "Test used for scaler: NO"
    )

    return mean, std


